import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { MemoryStore } from '../lib/store.js';

const previous = process.env.FEIYU_PREVIOUS_V060_PACKAGE ?? path.resolve(import.meta.dirname, '../../release-v060-install/package');
test('actual released 0.6.0 upgrades without changing immutable dictionaries, records, identity or receipts', { skip: !fs.existsSync(path.join(previous, 'package.json')) }, async t => {
  assert.equal(JSON.parse(fs.readFileSync(path.join(previous, 'package.json'), 'utf8')).version, '0.6.0');
  const { MemoryStore: PreviousStore } = await import(pathToFileURL(path.join(previous, 'lib/store.js')).href);
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'feiyu-v061-real-upgrade-'));
  const handles = [];
  t.after(() => { for (const handle of handles) handle.close(); assert.equal(path.dirname(path.resolve(dataDir)), path.resolve(os.tmpdir())); fs.rmSync(dataDir, { recursive: true, force: true }); });
  const options = { dataDir, instanceId: 'synthetic-v060-upgrade', now: () => new Date('2026-10-24T12:00:00Z') };
  const old = new PreviousStore(options); handles.push(old);
  const capture = { id: 'capture-before', pool: 'a', role: 'user', records: [{ id: 'raw-before', pool: 'a', role: 'user', sessionId: 'session-before', turnId: 'turn-before', text: '这是升级前保存的原文。', recordedAt: '2026-10-24T11:00:00Z' }] };
  old.captureMessage(capture);
  old.writeEntry({ id: 'before-entry', kind: 'memory', text: '明确的旧记忆', sources: [{ rawId: 'raw-before', quote: '升级前保存的原文' }] });
  old.linkThread({ requestId: 'before-link', threadId: 'ongoing', title: '旧事项', entries: [{ id: 'before-entry', version: 1 }], reason: '保持旧事项线' });
  old.setPreference({ requestId: 'before-preference', id: 'preference-before', expectedVersion: 0, action: 'set', topic: '色彩', stance: 'like', text: '我喜欢蓝色', reason: '升级合成数据' });
  old.writeKnowledge({ requestId: 'before-knowledge', id: 'knowledge-before', purpose: '合成知识', method: '已读教程', conditions: ['合成环境'], validationStatus: 'learned', externalSources: [{ url: 'https://example.com/reference' }], reason: '保留独立经验池' });
  const dictionaries = new Map(fs.readdirSync(path.join(dataDir, 'dict')).map(name => [name, fs.readFileSync(path.join(dataDir, 'dict', name))]));
  const tables = old.db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT IN ('projection_pending','dirty_days','sqlite_sequence') ORDER BY name").all().map(row => row.name);
  const snapshot = store => Object.fromEntries(tables.map(table => { assert.match(table, /^[a-z_][a-z0-9_]*$/u); return [table, createHash('sha256').update(JSON.stringify(store.db.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all())).digest('hex')]; }));
  const before = snapshot(old); old.close();
  const upgraded = new MemoryStore(options); handles.push(upgraded);
  assert.deepEqual(snapshot(upgraded), before);
  for (const [name, bytes] of dictionaries) assert.deepEqual(fs.readFileSync(path.join(dataDir, 'dict', name)), bytes, `Immutable dictionary ${name} changed`);
  assert.equal(upgraded.verifyCaptureMessage(capture), true);
  assert.equal(upgraded.readThread({ threadId: 'ongoing' }).items[0].id, 'before-entry');
  upgraded.linkThread({ requestId: 'new-raw-link', threadId: 'ongoing', rawIds: ['raw-before'], reason: '新版本挂接旧原文' });
  assert.equal(upgraded.getRaw('raw-before').threads[0].threadId, 'ongoing');
  assert.equal(upgraded.getRaw('raw-before').text, capture.records[0].text);
  assert.equal(upgraded.verifyCaptureMessage(capture), true);
  for (const [name, bytes] of dictionaries) assert.deepEqual(fs.readFileSync(path.join(dataDir, 'dict', name)), bytes);
});
